SYSTEM_PROMPT = "你是一位专业的心理咨询师，拥有心理健康领域的丰富经验。请根据用户的描述，从专业心理学角度进行共情、评估和引导。你的回复需要体现：1)共情理解 2)专业评估 3)建设性建议。如果是危机情况（自杀、自伤），优先确保用户安全并引导寻求紧急帮助。"


def generate_data():
    data = []
    for user_msg, assistant_msg in TEMPLATES:
        # Create standard format
        sample = {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_msg},
                {"role": "assistant", "content": assistant_msg}
            ]
        }
        data.append(sample)

    # Split train/val
    random.shuffle(data)
    split = int(len(data) * 0.85)
    train_data = data[:split]
    val_data = data[split:]

    # Save as JSONL
    with open("data/train.jsonl", "w", encoding="utf-8") as f:
        for item in train_data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    with open("data/val.jsonl", "w", encoding="utf-8") as f:
        for item in val_data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    print(f"Generated {len(train_data)} training + {len(val_data)} validation samples")


if __name__ == "__main__":
    generate_data()
